const VOWELS = "аеёиоуыэюя";

/** «в Казани»; неизвестное название без надёжного правила — «в городе Энск». */
export function inCity(name: string): string {
  const known = IN_CITY[name];
  if (known) return known;
  // «во» перед «в»/«ф» с согласной: во Всеволожске, во Фрязине.
  const prep = /^[ВФ]/.test(name) && !VOWELS.includes(name[1]?.toLowerCase() ?? "") ? "во" : "в";
  if (/^[А-ЯЁ][а-яё]+$/.test(name)) {
    // Согласная на конце: Омск → Омске. Без беглых гласных (Елец → Ельце, Орёл → Орле)
    // и без -й (Грозный).
    if (/[бвгджзклмнпрстфхчшщ]$/.test(name) && !/(ец|ок|ёл|ел)$/.test(name)) return `${prep} ${name}е`;
    // -а после согласной: Анапа → Анапе, Чита → Чите.
    if (/[бвгджзклмнпрстфхчшщ]а$/.test(name)) return `${prep} ${name.slice(0, -1)}е`;
  }
  return `в городе ${name}`;
}
